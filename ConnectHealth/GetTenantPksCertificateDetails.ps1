# 2. Request an ARM token using the context selected during sign-in.
$profile = Get-AzContext -ErrorAction Stop
if ([string]::IsNullOrWhiteSpace($profile.Account.Id) -or [string]::IsNullOrWhiteSpace($profile.Tenant.Id))
{
    Connect-AzAccount -ErrorAction Stop | Out-Null
    $profile = Get-AzContext -ErrorAction Stop
}

$signedInTenantId = $profile.Tenant.Id
if ([string]::IsNullOrWhiteSpace($profile.Account.Id) -or [string]::IsNullOrWhiteSpace($signedInTenantId))
{
    throw 'No Azure tenant context is available. Run Connect-AzAccount with your desired parameters first.'
}

$token = Get-AzAccessToken -ResourceUrl 'https://management.azure.com/' `
    -TenantId $signedInTenantId -DefaultProfile $profile -AsSecureString -ErrorAction Stop

if ($token.Token -isnot [System.Security.SecureString] -or $token.Token.Length -eq 0)
{
    throw 'Token acquisition did not return a secure access token. Update Az.Accounts and try again.'
}

# 3. Get the tenant configuration without printing the full tenant response.
$requestParameters = @{
    Uri = 'https://management.azure.com/providers/Microsoft.ADHybridHealthService/configuration?api-version=2014-01-01'
    Method = 'Get'
    Headers = @{ Accept = 'application/json' }
    MaximumRedirection = 0
    ErrorAction = 'Stop'
}

$certificate = $null
try
{
    if ($PSVersionTable.PSVersion.Major -ge 7)
    {
        $requestParameters.Authentication = 'Bearer'
        $requestParameters.Token = $token.Token
    }
    else
    {
        $credential = New-Object System.Management.Automation.PSCredential('Bearer', $token.Token)
        $requestParameters.Headers.Authorization = 'Bearer ' + $credential.GetNetworkCredential().Password
    }

    $tenantResponse = Invoke-RestMethod @requestParameters
    if ($null -eq $tenantResponse)
    {
        throw 'GetTenant returned no tenant response.'
    }

    $certBase64 = $tenantResponse.pksCertificate
    if ($null -ne $certBase64 -and $certBase64 -isnot [string])
    {
        throw 'The pksCertificate field must be a Base64 string.'
    }

    if ([string]::IsNullOrWhiteSpace($certBase64))
    {
        Write-Warning 'The tenant does not have a populated pksCertificate field.'
        return
    }

    # 4. Decode the PKS payload and remove its wrapper using byte 4 plus 8.
    try
    {
        $payload = [Convert]::FromBase64String($certBase64)
    }
    catch [FormatException]
    {
        throw 'The pksCertificate field is not valid Base64.'
    }

    if ($payload.Length -lt 8)
    {
        throw 'The pksCertificate payload is too short to contain the expected PKS header.'
    }

    $certificateOffset = [int]$payload[4] + 8
    if ($certificateOffset -ge $payload.Length)
    {
        throw 'The pksCertificate header does not leave any certificate data in the payload.'
    }

    $certificateBytes = New-Object byte[] ($payload.Length - $certificateOffset)
    [Array]::Copy($payload, $certificateOffset, $certificateBytes, 0, $certificateBytes.Length)

    # 5. Load in memory only and print certificate details as JSON.
    $certificate = [System.Security.Cryptography.X509Certificates.X509Certificate2]::new(
        $certificateBytes,
        [string]::Empty,
        [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]::EphemeralKeySet)

    [pscustomobject]@{
        Subject = $certificate.Subject
        Issuer = $certificate.Issuer
        Thumbprint = $certificate.Thumbprint
        SerialNumber = $certificate.SerialNumber
        NotBeforeUtc = $certificate.NotBefore.ToUniversalTime().ToString('o')
        NotAfterUtc = $certificate.NotAfter.ToUniversalTime().ToString('o')
        Version = $certificate.Version
        HasPrivateKey = $certificate.HasPrivateKey
        SignatureAlgorithm = $certificate.SignatureAlgorithm.FriendlyName
        PublicKeyAlgorithm = $certificate.PublicKey.Oid.FriendlyName
        Extensions = @(
            foreach ($extension in $certificate.Extensions)
            {
                [pscustomobject]@{
                    Oid = $extension.Oid.Value
                    Name = $extension.Oid.FriendlyName
                    Critical = $extension.Critical
                    Value = $extension.Format($false)
                }
            }
        )
    } | ConvertTo-Json -Depth 50
}
finally
{
    if ($null -ne $certificate)
    {
        $certificate.Dispose()
    }

    $requestParameters.Headers.Clear()
    $requestParameters.Clear()
    $credential = $null
    $token = $null
}

